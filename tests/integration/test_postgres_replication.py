def test_subscription_identity_drift_rejected(replication):
    replication["barrier"]()
    with pytest.raises(ContractError, match="Subscription"):
        replication["inspect"](replace(replication["registration"], subscription_oid=1))


def test_barrier_alone_is_not_data_equality_or_sequence_safety(replication):
    replication["barrier"]()
    with psycopg.connect(replication["target"], autocommit=True) as conn:
        conn.execute(
            "UPDATE public.messages SET body='changed outside replication' WHERE id=1"
        )
        assert conn.execute(
            "SELECT last_value,is_called FROM public.messages_id_seq"
        ).fetchone() == (1, False)
    receipt = replication["inspect"]()
    assert not receipt["cutover_authorized"]
    assert {
        "sequence-safety",
        "data-content-equality",
        "all-writer-fencing",
        "reverse-recovery",
    } <= set(receipt["not_verified"])


def dataset_reader(replication, side):
    from sova.adapters.postgres_dataset import PostgresDatasetRegistration

    endpoint = getattr(replication["registration"], side)
    with psycopg.connect(replication[side], autocommit=True) as conn:
        conn.execute(
            sql.SQL("GRANT SELECT ON ALL SEQUENCES IN SCHEMA public TO {}").format(
                sql.Identifier(endpoint.reader_role)
            )
        )
        definition = table_definition(conn, "public", "messages")
    r = replication["registration"]
    registration = PostgresDatasetRegistration(
        endpoint.scope,
        r.revisions,
        endpoint.connection_ref,
        endpoint.database_name,
        endpoint.database_oid,
        endpoint.system_identifier,
        endpoint.reader_role,
        "public",
        "messages",
        definition["table_oid"],
        definition["schema_digest"],
        definition["columns"],
        definition["primary_key"],
        r.issued_at,
        r.valid_until,
        allow_private_unix_fixture=True,
    )
    return registration, lambda ref: psycopg.connect(
        replication[side], user=endpoint.reader_role
    )


def test_real_sequence_drift_blocks_then_explicit_operator_repair_is_observed(
    replication,
):
    from sova.adapters.postgres_sequences import (
        PostgresSequenceObserver,
        compare_sequence_observations,
    )

    replication["barrier"]()
    readers = [dataset_reader(replication, side) for side in ("source", "target")]

    def observations():
        return [
            PostgresSequenceObserver(
                reg,
                connect=connect,
                authorize=lambda *args: None,
                authenticate_registration=lambda reg: None,
                clock=lambda: datetime.now(UTC),
                monotonic=time.monotonic,
            ).observe("operator")
            for reg, connect in readers
        ]

    source, target = observations()
    assert source.next_value == 4 and target.next_value == 1
    assert not compare_sequence_observations(source, target, now=datetime.now(UTC))[
        "observed_collision_safe"
    ]
    with psycopg.connect(replication["target"], autocommit=True) as operator:
        operator.execute("SELECT setval('public.messages_id_seq',3,true)")
    source, target = observations()
    result = compare_sequence_observations(source, target, now=datetime.now(UTC))
    assert result["observed_collision_safe"] and not result["cutover_authorized"]
    with readers[1][1]("target-reader") as conn:
        with pytest.raises(psycopg.errors.InsufficientPrivilege):
            conn.execute("SELECT nextval('public.messages_id_seq')")


def test_same_count_corruption_detected_even_after_barrier_arrives(replication):
    from sova.adapters.postgres_dataset import PostgresDatasetReader
    from sova.domain.data_manifest import compare_manifests

    replication["barrier"]()
    readers = [dataset_reader(replication, side) for side in ("source", "target")]

    def inspect():
        manifests = [
            PostgresDatasetReader(
                reg,
                connect=connect,
                authorize=lambda *args: None,
                authenticate_registration=lambda reg: None,
                clock=lambda: datetime.now(UTC),
                monotonic=time.monotonic,
            ).snapshot("operator", boundary_id=replication["boundary"])["manifest"]
            for reg, connect in readers
        ]
        return compare_manifests(*manifests, now=datetime.now(UTC))

    assert inspect()["content_equal"]
    with psycopg.connect(replication["target"], autocommit=True) as conn:
        conn.execute(
            "UPDATE public.messages SET body='corrupted but same row count' WHERE id=1"
        )
    assert replication["inspect"]()["barrier_arrived"]
    report = inspect()
    assert not report["content_equal"] and not report["cutover_authorized"]
