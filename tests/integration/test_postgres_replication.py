"""Real logical replication between two disposable databases, not cloud migration.

No existing database is modified. Superuser fixture setup is never given to the
read-only production observer. Requires wal_level=logical in the isolated test
cluster; native test harnesses may enable it explicitly.
"""

from dataclasses import replace
from datetime import UTC, datetime, timedelta
import time
from uuid import uuid4

import psycopg
from psycopg import sql
from psycopg.conninfo import make_conninfo
import pytest

from sova.adapters.postgres_dataset import table_definition
from sova.adapters.postgres_replication import (
    ReplicationEndpoint,
    ReplicatedTable,
    ReplicationRegistration,
    PostgresReplicationObserver,
)
from sova.domain.contracts import ContractError, ResourceScope
from sova.domain.evidence import RevisionSet

pytestmark = pytest.mark.postgres


@pytest.fixture
def replication(postgres_database):
    base, _ = postgres_database
    token = uuid4().hex
    names = {
        key: key + "_" + token
        for key in (
            "source",
            "target",
            "replicator",
            "reader_source",
            "reader_target",
            "publication",
            "subscription",
            "slot",
        )
    }
    with psycopg.connect(base, autocommit=True) as root:
        if root.execute("SHOW wal_level").fetchone()[0] != "logical":
            pytest.skip("isolated PostgreSQL must explicitly enable logical WAL")
        for key in ("replicator", "reader_source", "reader_target"):
            root.execute(
                sql.SQL(
                    "CREATE ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS NOINHERIT {}"
                ).format(
                    sql.Identifier(names[key]),
                    sql.SQL("REPLICATION" if key == "replicator" else "NOREPLICATION"),
                )
            )
        for key in ("source", "target"):
            root.execute(
                sql.SQL("CREATE DATABASE {}").format(sql.Identifier(names[key]))
            )
    source = make_conninfo(base, dbname=names["source"])
    target = make_conninfo(base, dbname=names["target"])
    connections = {}
    try:
        endpoints = []
        defs = []
        for key, dsn in (("source", source), ("target", target)):
            with psycopg.connect(dsn, autocommit=True) as conn:
                conn.execute(
                    "CREATE TABLE public.messages(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body text NOT NULL)"
                )
                conn.execute(
                    "CREATE TABLE public.migration_barriers(boundary_id uuid PRIMARY KEY, plan_digest text NOT NULL, writer_epoch bigint NOT NULL)"
                )
                reader = names["reader_" + key]
                conn.execute(
                    sql.SQL("GRANT SELECT ON ALL TABLES IN SCHEMA public TO {}").format(
                        sql.Identifier(reader)
                    )
                )
                conn.execute(
                    sql.SQL(
                        "GRANT EXECUTE ON FUNCTION pg_catalog.pg_control_system() TO {}"
                    ).format(sql.Identifier(reader))
                )
                if key == "target":
                    conn.execute(
                        sql.SQL(
                            "GRANT SELECT(oid,subdbid,subname,subenabled,subpublications) ON pg_catalog.pg_subscription TO {}"
                        ).format(sql.Identifier(reader))
                    )
                identity = conn.execute(
                    "SELECT current_database(),d.oid,c.system_identifier::text FROM pg_catalog.pg_database d CROSS JOIN pg_catalog.pg_control_system() c WHERE d.datname=current_database()"
                ).fetchone()
                endpoints.append(
                    ReplicationEndpoint(
                        ResourceScope("tenant-test", "consultation", key, "postgres"),
                        key + "-reader",
                        *identity,
                        reader,
                        True,
                    )
                )
                defs.append(
                    {
                        name: table_definition(conn, "public", name)
                        for name in ("messages", "migration_barriers")
                    }
                )
                connections[key + "-reader"] = make_conninfo(dsn, user=reader)
        replication_dsn = make_conninfo(
            source,
            user=names["replicator"],
            application_name="sova-replication-fixture",
        )
        with psycopg.connect(source, autocommit=True) as conn:
            conn.execute(
                "INSERT INTO public.messages(body) VALUES ('synthetic initial message'),('second message')"
            )
            conn.execute(
                sql.SQL("GRANT SELECT ON ALL TABLES IN SCHEMA public TO {}").format(
                    sql.Identifier(names["replicator"])
                )
            )
            conn.execute(
                sql.SQL(
                    "CREATE PUBLICATION {} FOR TABLE public.messages, public.migration_barriers"
                ).format(sql.Identifier(names["publication"]))
            )
            puboid = conn.execute(
                "SELECT oid FROM pg_catalog.pg_publication WHERE pubname=%s",
                (names["publication"],),
            ).fetchone()[0]
            conn.execute(
                "SELECT pg_create_logical_replication_slot(%s,%s)",
                (names["slot"], "pgoutput"),
            )
        with psycopg.connect(target, autocommit=True) as conn:
            conn.execute(
                sql.SQL(
                    "CREATE SUBSCRIPTION {} CONNECTION {} PUBLICATION {} WITH(create_slot=false,slot_name={},copy_data=true)"
                ).format(
                    sql.Identifier(names["subscription"]),
                    sql.Literal(replication_dsn),
                    sql.Identifier(names["publication"]),
                    sql.Literal(names["slot"]),
                )
            )
            suboid = conn.execute(
                "SELECT oid FROM pg_catalog.pg_subscription WHERE subname=%s",
                (names["subscription"],),
            ).fetchone()[0]
            deadline = time.monotonic() + 20
            while time.monotonic() < deadline:
                states = conn.execute(
                    "SELECT srsubstate FROM pg_catalog.pg_subscription_rel WHERE srsubid=%s",
                    (suboid,),
                ).fetchall()
                if len(states) == 2 and all(row[0] == "r" for row in states):
                    break
                time.sleep(0.05)
            else:
                raise AssertionError(
                    "Own logical replication initial copy did not become ready"
                )
        now = datetime.now(UTC)
        registration = ReplicationRegistration(
            *endpoints,
            RevisionSet(*("a" * 64,) * 4),
            names["publication"],
            puboid,
            names["subscription"],
            suboid,
            tuple(
                ReplicatedTable(
                    "public",
                    name,
                    defs[0][name]["table_oid"],
                    defs[1][name]["table_oid"],
                    defs[0][name]["schema_digest"],
                )
                for name in defs[0]
            ),
            "public",
            "migration_barriers",
            now - timedelta(seconds=1),
            now + timedelta(minutes=3),
        )
        boundary = str(uuid4())
        plan = "b" * 64

        def barrier():
            with psycopg.connect(source, autocommit=True) as conn:
                conn.execute(
                    "INSERT INTO public.messages(body) VALUES ('live change after initial copy')"
                )
                conn.execute(
                    "INSERT INTO public.migration_barriers VALUES(%s,%s,%s)",
                    (boundary, plan, 7),
                )
            with psycopg.connect(target, autocommit=True) as conn:
                deadline = time.monotonic() + 10
                while time.monotonic() < deadline:
                    if (
                        conn.execute(
                            "SELECT count(*) FROM public.migration_barriers WHERE boundary_id=%s",
                            (boundary,),
                        ).fetchone()[0]
                        == 1
                    ):
                        return
                    time.sleep(0.05)
                raise AssertionError("Own barrier did not replicate")

        def inspect(reg=registration, **changes):
            args = {"boundary_id": boundary, "plan_digest": plan, "writer_epoch": 7}
            args.update(changes)
            return PostgresReplicationObserver(
                reg,
                connect=lambda ref: psycopg.connect(connections[ref]),
                authorize=lambda *args: None,
                authenticate_registration=lambda reg: None,
                clock=lambda: datetime.now(UTC),
                monotonic=time.monotonic,
            ).inspect("fixture-operator", **args)

        yield {
            "registration": registration,
            "inspect": inspect,
            "barrier": barrier,
            "source": source,
            "target": target,
            "names": names,
            "boundary": boundary,
            "plan": plan,
        }
    finally:
        with psycopg.connect(target, autocommit=True) as conn:
            if conn.execute(
                "SELECT 1 FROM pg_catalog.pg_subscription WHERE subname=%s",
                (names["subscription"],),
            ).fetchone():
                conn.execute(
                    sql.SQL("ALTER SUBSCRIPTION {} DISABLE").format(
                        sql.Identifier(names["subscription"])
                    )
                )
                conn.execute(
                    sql.SQL("ALTER SUBSCRIPTION {} SET(slot_name=NONE)").format(
                        sql.Identifier(names["subscription"])
                    )
                )
                conn.execute(
                    sql.SQL("DROP SUBSCRIPTION {}").format(
                        sql.Identifier(names["subscription"])
                    )
                )
        with psycopg.connect(base, autocommit=True) as root:
            for key in ("target", "source"):
                root.execute(
                    sql.SQL("DROP DATABASE {} WITH(FORCE)").format(
                        sql.Identifier(names[key])
                    )
                )
            for key in ("replicator", "reader_source", "reader_target"):
                root.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(names[key])))


def test_real_initial_copy_live_change_and_exact_barrier(replication):
    replication["barrier"]()
    result = replication["inspect"]()
    assert result["barrier_arrived"] and result["tables_observed"] == 2
    assert not result["cutover_authorized"]
    with psycopg.connect(replication["target"]) as conn:
        assert conn.execute("SELECT count(*) FROM public.messages").fetchone()[0] == 3
    assert "data-content-equality" in result["not_verified"]


