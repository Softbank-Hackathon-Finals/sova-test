-- Run with a separate migration owner. The application never creates its schema.
CREATE SCHEMA IF NOT EXISTS consultation;
CREATE TABLE consultation.users (
    user_id uuid PRIMARY KEY,
    display_name text NOT NULL,
    role text NOT NULL CHECK (role IN ('customer','counselor')),
    disabled boolean NOT NULL DEFAULT false
);
CREATE TABLE consultation.invitations (
    code_hash text PRIMARY KEY CHECK (length(code_hash)=64),
    user_id uuid NOT NULL REFERENCES consultation.users,
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz
);
CREATE TABLE consultation.sessions (
    token_hash text PRIMARY KEY CHECK (length(token_hash)=64),
    csrf_hash text NOT NULL CHECK (length(csrf_hash)=64),
    user_id uuid NOT NULL REFERENCES consultation.users,
    expires_at timestamptz NOT NULL
);
CREATE TABLE consultation.rooms (
    room_id uuid PRIMARY KEY,
    customer_id uuid NOT NULL REFERENCES consultation.users,
    counselor_id uuid NOT NULL REFERENCES consultation.users,
    last_sequence bigint NOT NULL DEFAULT 0 CHECK (last_sequence >= 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE consultation.control (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    writes_enabled boolean NOT NULL,
    writer_epoch bigint NOT NULL CHECK (writer_epoch>0),
    execution_epoch bigint NOT NULL DEFAULT 0 CHECK (execution_epoch>=0),
    last_command_digest text CHECK (last_command_digest ~ '^[0-9a-f]{64}$')
);
INSERT INTO consultation.control(singleton,writes_enabled,writer_epoch) VALUES (true,true,1);
CREATE TABLE consultation.messages (
    message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id uuid NOT NULL REFERENCES consultation.rooms,
    author_id uuid NOT NULL REFERENCES consultation.users,
    client_request_id uuid NOT NULL,
    sequence bigint NOT NULL CHECK (sequence>0),
    content text NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 8192),
    writer_epoch bigint NOT NULL CHECK (writer_epoch>0),
    environment text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(author_id,client_request_id),
    UNIQUE(room_id,sequence)
);
CREATE TABLE consultation.attachments (
    attachment_id uuid PRIMARY KEY,
    room_id uuid NOT NULL REFERENCES consultation.rooms,
    author_id uuid NOT NULL REFERENCES consultation.users,
    filename text NOT NULL,
    content_digest text NOT NULL CHECK (length(content_digest)=64),
    byte_length integer NOT NULL CHECK (byte_length BETWEEN 1 AND 1048576),
    state text NOT NULL CHECK (state IN ('prepared','ready','failed')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE consultation.audit (
    event_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_id uuid NOT NULL REFERENCES consultation.users,
    event text NOT NULL,
    room_id uuid,
    request_id uuid,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
